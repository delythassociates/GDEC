"""
Single-QoI Decision Evaluator for GDEC Decision Sufficiency Engine.
Implements Bayesian expected loss minimization against asymmetric costs,
integrates asymptotic DWR discretization error indicators as distinct quality gates,
strictly enforces EvidenceAssessment requirements, and prevents bypassing mandatory gates.
"""

from __future__ import annotations
import math
from enum import Enum
from dataclasses import dataclass, field
from typing import Dict, Any, Optional, List
import numpy as np
from scipy.special import ndtr

from gdec.dse.contract import DecisionContract, PredictiveDistribution
from gdec.dse.evidence import EvidenceAssessment, ValidationStatus
from gdec.dse.exceptions import DecisionRefusalError


class DecisionRecommendation(str, Enum):
    """Decision recommendations generated by the evaluator."""
    RELEASE = "RELEASE"                              # Conditional recommendation: expected loss of release is lower
    REJECT = "REJECT"                                # Conditional recommendation: expected loss of rejection is lower
    REFINE = "REFINE"                                # Mandatory quality breach or narrow margin; further compute recommended
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"  # Missing evidence, unattested assumptions, or refused contract


@dataclass(frozen=True)
class DecisionEvaluationResult:
    """Structured, audit-ready result of single-QoI decision evaluation."""
    recommendation: DecisionRecommendation
    expected_loss_release: float
    expected_loss_reject: float
    probability_safe: float
    probability_fail: float
    decision_margin: float
    threshold_value: float
    qoi_mean: float
    qoi_std: float
    dwr_asymptotic_indicator: Optional[float] = None
    refusal_reason: Optional[str] = None
    diagnostics: Dict[str, Any] = field(default_factory=dict)

    def is_conclusive(self) -> bool:
        """True if the decision is an actionable RELEASE or REJECT."""
        return self.recommendation in (DecisionRecommendation.RELEASE, DecisionRecommendation.REJECT)

    def to_dict(self) -> Dict[str, Any]:
        """Convert evaluation result to dictionary."""
        return {
            "recommendation": self.recommendation.value,
            "expected_loss_release": self.expected_loss_release,
            "expected_loss_reject": self.expected_loss_reject,
            "probability_safe": self.probability_safe,
            "probability_fail": self.probability_fail,
            "decision_margin": self.decision_margin,
            "threshold_value": self.threshold_value,
            "qoi_mean": self.qoi_mean,
            "qoi_std": self.qoi_std,
            "dwr_asymptotic_indicator": self.dwr_asymptotic_indicator,
            "refusal_reason": self.refusal_reason,
            "diagnostics": self.diagnostics,
        }


class SingleQoIEvaluator:
    """
    Evaluator for single Quantity of Interest (QoI) decision problems under normal uncertainty.
    Minimizes asymmetric Bayesian expected loss:
        R_release = C_FA * P_fail
        R_reject  = C_FR * P_safe
    Enforces that required evidence categories, model assumptions, and numerical quality
    gates are strictly verified before recommending an actionable decision.
    """

    def __init__(self, contract: DecisionContract) -> None:
        self.contract = contract

    def evaluate(
        self,
        predictive_distribution: Optional[PredictiveDistribution] = None,
        evidence_assessment: Optional[EvidenceAssessment] = None,
        dwr_indicator: Optional[float] = None,
        raise_on_refusal: bool = False,
    ) -> DecisionEvaluationResult:
        """
        Evaluate the decision contract against supplied evidence and predictive distribution.

        Parameters
        ----------
        predictive_distribution : PredictiveDistribution, optional
            QoI predictive distribution (mean, std, unit, provenance).
            If omitted, uses contract.predictive_distribution.
        evidence_assessment : EvidenceAssessment, optional
            Structured evidence package containing verified records, validated assumptions,
            model reference, and operating domain. Mandatory for actionable decisions.
        dwr_indicator : float, optional
            Asymptotic goal-oriented DWR error indicator |J - J_h| from FEM.
            Must NOT be treated as a guaranteed bound or merged into Gaussian std.
        raise_on_refusal : bool, default False
            If True, raise DecisionRefusalError instead of returning INSUFFICIENT_EVIDENCE.

        Returns
        -------
        DecisionEvaluationResult (conditional decision recommendation)
        """
        # ----------------------------------------------------------------------
        # GATE 1: Predictive Uncertainty Distribution Verification
        # ----------------------------------------------------------------------
        dist = predictive_distribution or self.contract.predictive_distribution

        if dist is None:
            reason = "Missing predictive uncertainty distribution (both mean and std must be supplied with explicit provenance)."
            if raise_on_refusal:
                raise DecisionRefusalError(reason)
            return self._insufficient(reason)

        mu = dist.mean
        sigma = dist.std

        # Finiteness and validity checks
        if not (math.isfinite(mu) and math.isfinite(sigma) and math.isfinite(self.contract.criterion.limit)):
            reason = f"Non-finite input values detected: mean={mu}, std={sigma}, limit={self.contract.criterion.limit}"
            if raise_on_refusal:
                raise DecisionRefusalError(reason)
            return self._insufficient(reason, mu=mu, sigma=sigma)

        if sigma < 0.0:
            reason = f"Invalid negative standard deviation: sigma={sigma}"
            if raise_on_refusal:
                raise DecisionRefusalError(reason)
            return self._insufficient(reason, mu=mu, sigma=sigma)

        # Unit consistency
        if dist.unit.strip().lower() != self.contract.qoi.unit.strip().lower():
            reason = (
                f"Predictive distribution unit '{dist.unit}' does not match "
                f"contract QoI unit '{self.contract.qoi.unit}'."
            )
            if raise_on_refusal:
                raise DecisionRefusalError(reason)
            return self._insufficient(reason, mu=mu, sigma=sigma)

        # ----------------------------------------------------------------------
        # GATE 2: Evidence Assessment & Provenance Verification
        # ----------------------------------------------------------------------
        if evidence_assessment is None:
            reason = (
                "Missing EvidenceAssessment: Decision Contract requires an explicit, auditable "
                "EvidenceAssessment package before any decision recommendation can be rendered."
            )
            if raise_on_refusal:
                raise DecisionRefusalError(reason)
            return self._insufficient(reason, mu=mu, sigma=sigma)

        # Check record-level eligibility for all required categories
        records_ok, reports_by_cat, record_refusal_reasons = evidence_assessment.evaluate_record_eligibility(
            required_categories=self.contract.evidence.required_categories,
            target_model=self.contract.qoi.model_reference or "",
            target_domain=self.contract.evidence.applicable_domain or "",
            required_status=self.contract.evidence.validation_status or "verified",
        )
        if not records_ok:
            reason = f"Evidence record eligibility check failed: {'; '.join(record_refusal_reasons)}"
            if raise_on_refusal:
                raise DecisionRefusalError(
                    reason,
                    diagnostics={"record_reports": reports_by_cat, "refusal_reasons": record_refusal_reasons},
                )
            return self._insufficient(
                reason,
                mu=mu,
                sigma=sigma,
                diagnostics={"record_reports": reports_by_cat, "refusal_reasons": record_refusal_reasons},
            )

        # Check model assumptions attestation
        unattested_assumptions = [
            asm for asm in self.contract.evidence.model_assumptions
            if asm not in evidence_assessment.validated_assumptions
        ]
        if unattested_assumptions:
            reason = f"Unattested model assumptions: {unattested_assumptions}"
            if raise_on_refusal:
                raise DecisionRefusalError(reason, diagnostics={"unattested_assumptions": unattested_assumptions})
            return self._insufficient(reason, mu=mu, sigma=sigma, diagnostics={"unattested_assumptions": unattested_assumptions})

        # Check domain applicability
        if evidence_assessment.applicable_domain.strip().lower() != self.contract.evidence.applicable_domain.strip().lower():
            reason = (
                f"Domain applicability mismatch: Evidence is valid for domain '{evidence_assessment.applicable_domain}', "
                f"but contract requires operating envelope '{self.contract.evidence.applicable_domain}'."
            )
            if raise_on_refusal:
                raise DecisionRefusalError(reason)
            return self._insufficient(reason, mu=mu, sigma=sigma)

        # Check model reference
        if self.contract.qoi.model_reference:
            if evidence_assessment.model_reference.strip().lower() != self.contract.qoi.model_reference.strip().lower():
                reason = (
                    f"Model reference mismatch: Evidence was generated for model '{evidence_assessment.model_reference}', "
                    f"but contract specifies '{self.contract.qoi.model_reference}'."
                )
                if raise_on_refusal:
                    raise DecisionRefusalError(reason)
                return self._insufficient(reason, mu=mu, sigma=sigma)

        # Check validation status requirement
        contract_val_status = self.contract.evidence.validation_status.lower().strip()
        if contract_val_status in ("validated", "independently_validated"):
            ev_status = evidence_assessment.validation_status.value.lower()
            if ev_status not in ("validated", "independently_validated"):
                reason = (
                    f"Insufficient validation credibility: Contract specifies status '{self.contract.evidence.validation_status}', "
                    f"but evidence assessment provides '{evidence_assessment.validation_status.value}'."
                )
                if raise_on_refusal:
                    raise DecisionRefusalError(reason)
                return self._insufficient(reason, mu=mu, sigma=sigma)

        # ----------------------------------------------------------------------
        # GATE 3: Numerical Quality & DWR Discretization Gate
        # ----------------------------------------------------------------------
        dwr_breached = False
        dwr_rel = None

        dwr_required = any(
            cat.strip().lower() in ("discretization_error", "mesh_convergence", "dwr", "numerical_quality")
            for cat in self.contract.evidence.required_categories
        )

        effective_dwr = dwr_indicator
        if effective_dwr is None and evidence_assessment is not None:
            # Look for numerical_metric in discretization_error / mesh_convergence records
            for rec in evidence_assessment.evidence_records:
                if rec.category.strip().lower() in ("discretization_error", "mesh_convergence", "dwr"):
                    if rec.numerical_metric is not None and math.isfinite(rec.numerical_metric):
                        effective_dwr = rec.numerical_metric
                        break

        if dwr_required and effective_dwr is None:
            reason = (
                "Mandatory Discretization Quality Evidence Missing: Decision Contract specifies "
                f"numerical_quality_threshold ({self.contract.evidence.numerical_quality_threshold}) or requires "
                "discretization error assessment, but no DWR error indicator or valid numerical_metric was provided."
            )
            if raise_on_refusal:
                raise DecisionRefusalError(reason)
            return self._insufficient(reason, mu=mu, sigma=sigma)

        if effective_dwr is not None:
            if not math.isfinite(effective_dwr) or effective_dwr < 0.0:
                reason = f"Invalid DWR indicator: {effective_dwr} (must be non-negative finite)"
                if raise_on_refusal:
                    raise DecisionRefusalError(reason)
                return self._insufficient(reason, mu=mu, sigma=sigma)

            # Determine reference scale (Option B: explicit reference scale)
            if evidence_assessment.reference_scale is not None and evidence_assessment.reference_scale > 0.0:
                ref_scale = evidence_assessment.reference_scale
            elif abs(self.contract.criterion.limit) > 1e-12:
                # Fallback to absolute threshold limit if reference scale not supplied
                ref_scale = abs(self.contract.criterion.limit)
            else:
                reason = "Cannot assess relative DWR error: No explicit positive reference_scale provided and threshold is near-zero."
                if raise_on_refusal:
                    raise DecisionRefusalError(reason)
                return self._insufficient(reason, mu=mu, sigma=sigma)

            dwr_rel = effective_dwr / ref_scale
            quality_tol = self.contract.evidence.numerical_quality_threshold
            if quality_tol is not None and dwr_rel > quality_tol:
                dwr_breached = True

        # ----------------------------------------------------------------------
        # GATE 4: Probabilities & Expected Loss Minimization
        # ----------------------------------------------------------------------
        op = self.contract.criterion.operator
        limit = self.contract.criterion.limit
        buffer = self.contract.criterion.safety_margin

        if op in ("<=", "<"):
            effective_limit = limit - buffer
        elif op in (">=", ">"):
            effective_limit = limit + buffer
        else:
            reason = f"Unsupported comparison operator '{op}'"
            if raise_on_refusal:
                raise DecisionRefusalError(reason)
            return self._insufficient(reason, mu=mu, sigma=sigma)

        if sigma == 0.0:
            if op in ("<=", "<"):
                is_safe = (mu <= effective_limit) if op == "<=" else (mu < effective_limit)
            else:
                is_safe = (mu >= effective_limit) if op == ">=" else (mu > effective_limit)
            p_safe = 1.0 if is_safe else 0.0
            p_fail = 0.0 if is_safe else 1.0
            margin = (effective_limit - mu) if op in ("<=", "<") else (mu - effective_limit)
        else:
            if op in ("<=", "<"):
                z = (effective_limit - mu) / sigma
                p_safe = float(ndtr(z))
                p_fail = float(ndtr(-z))
                margin = z
            else:
                z = (mu - effective_limit) / sigma
                p_safe = float(ndtr(z))
                p_fail = float(ndtr(-z))
                margin = z

        p_safe = max(0.0, min(1.0, p_safe))
        p_fail = max(0.0, min(1.0, p_fail))

        c_fa = self.contract.loss.cost_false_acceptance
        c_fr = self.contract.loss.cost_false_rejection

        r_release = c_fa * p_fail
        r_reject = c_fr * p_safe

        diagnostics = {
            "effective_limit": effective_limit,
            "safety_margin_applied": buffer,
            "dwr_relative_error": dwr_rel,
            "numerical_quality_threshold": self.contract.evidence.numerical_quality_threshold,
            "dwr_gate_breached": dwr_breached,
            "assessment_id": evidence_assessment.assessment_id,
            "record_reports": reports_by_cat,
        }

        # ----------------------------------------------------------------------
        # MANDATORY VERDICT PRECEDENCE (Cannot be bypassed)
        # ----------------------------------------------------------------------
        if dwr_breached:
            rec = DecisionRecommendation.REFINE
            refusal_msg = (
                f"Mandatory Quality Breach: Asymptotic DWR error indicator ({dwr_rel:.4%}) "
                f"exceeds contract quality threshold ({self.contract.evidence.numerical_quality_threshold:.4%}). "
                "Additional mesh refinement required before an actionable release decision can be considered."
            )
        elif r_release == r_reject:
            # Exact risk tie: conservative policy recommends REFINE
            rec = DecisionRecommendation.REFINE
            refusal_msg = "Exact Risk Tie: Expected loss of release equals rejection. Additional evidence required."
        elif sigma > 0.0 and abs(r_release - r_reject) / max(r_release, r_reject, 1e-12) < 0.05:
            # Narrow decision boundary (<5% difference)
            rec = DecisionRecommendation.REFINE
            refusal_msg = "Ambiguous Decision Margin: Difference between release and reject expected losses is < 5%."
        elif r_release < r_reject:
            rec = DecisionRecommendation.RELEASE
            refusal_msg = None
        else:
            rec = DecisionRecommendation.REJECT
            refusal_msg = None

        return DecisionEvaluationResult(
            recommendation=rec,
            expected_loss_release=r_release,
            expected_loss_reject=r_reject,
            probability_safe=p_safe,
            probability_fail=p_fail,
            decision_margin=margin,
            threshold_value=effective_limit,
            qoi_mean=mu,
            qoi_std=sigma,
            dwr_asymptotic_indicator=dwr_indicator,
            refusal_reason=refusal_msg,
            diagnostics=diagnostics,
        )

    def _insufficient(
        self,
        reason: str,
        mu: float = float("nan"),
        sigma: float = float("nan"),
        diagnostics: Optional[Dict[str, Any]] = None,
    ) -> DecisionEvaluationResult:
        return DecisionEvaluationResult(
            recommendation=DecisionRecommendation.INSUFFICIENT_EVIDENCE,
            expected_loss_release=float("nan"),
            expected_loss_reject=float("nan"),
            probability_safe=float("nan"),
            probability_fail=float("nan"),
            decision_margin=float("nan"),
            threshold_value=self.contract.criterion.limit,
            qoi_mean=mu if math.isfinite(mu) else float("nan"),
            qoi_std=sigma if math.isfinite(sigma) else float("nan"),
            refusal_reason=reason,
            diagnostics=diagnostics or {},
        )
